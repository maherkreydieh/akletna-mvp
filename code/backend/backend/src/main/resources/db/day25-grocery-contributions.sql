-- Preserve existing display rows as legacy planned requirements exactly once.
-- Their Ingredient IDs were never stored: do not guess identities from names.
DO $$
BEGIN
    IF to_regclass('grocery_lists') IS NOT NULL THEN
        LOCK TABLE grocery_lists,grocery_items IN SHARE ROW EXCLUSIVE MODE;
        ALTER TABLE grocery_lists ADD COLUMN IF NOT EXISTS contributions_initialized boolean NOT NULL DEFAULT false;
        CREATE TABLE IF NOT EXISTS grocery_contributions (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            grocery_list_id bigint NOT NULL REFERENCES grocery_lists(id),
            source varchar(30) NOT NULL,source_key varchar(100) NOT NULL,source_name varchar(255) NOT NULL,
            recipe_id bigint,servings integer,created_at timestamp(6) NOT NULL,
            CONSTRAINT uq_grocery_source_context UNIQUE(grocery_list_id,source_key)
        );
        CREATE TABLE IF NOT EXISTS grocery_contribution_lines (
            contribution_id bigint NOT NULL REFERENCES grocery_contributions(id) ON DELETE CASCADE,
            line_index integer NOT NULL,ingredient_id bigint,legacy_item_id bigint,
            ingredient_name varchar(255) NOT NULL,state varchar(40) NOT NULL,
            numerator numeric(80,0),denominator numeric(80,0),unit varchar(255),
            PRIMARY KEY(contribution_id,line_index)
        );
        IF EXISTS (SELECT 1 FROM grocery_items i JOIN grocery_lists l ON l.id=i.grocery_list_id
                   WHERE NOT l.contributions_initialized AND (i.quantity IS NULL OR i.quantity<0 OR i.quantity::text IN ('NaN','Infinity','-Infinity'))) THEN
            RAISE EXCEPTION 'Invalid legacy grocery quantities: migration stopped without changing data.';
        END IF;
        WITH inserted AS (
            INSERT INTO grocery_contributions(grocery_list_id,source,source_key,source_name,created_at)
            SELECT l.id,'PLANNED_MEAL','PLAN','Weekly meal plan (legacy)',CURRENT_TIMESTAMP FROM grocery_lists l
            WHERE NOT l.contributions_initialized AND EXISTS(SELECT 1 FROM grocery_items i WHERE i.grocery_list_id=l.id)
            RETURNING id,grocery_list_id
        )
        INSERT INTO grocery_contribution_lines(contribution_id,line_index,legacy_item_id,ingredient_name,state,numerator,denominator,unit)
        SELECT c.id,(row_number() OVER(PARTITION BY c.id ORDER BY i.id)-1)::integer,i.id,i.name,'REQUIRED',
               i.quantity::text::numeric*power(10::numeric,scale(i.quantity::text::numeric)),
               power(10::numeric,scale(i.quantity::text::numeric)),coalesce(i.unit,'')
        FROM inserted c JOIN grocery_items i ON i.grocery_list_id=c.grocery_list_id;
        UPDATE grocery_lists SET contributions_initialized=true WHERE NOT contributions_initialized;
    END IF;
END
$$@@
